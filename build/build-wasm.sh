#!/usr/bin/env bash
# Build the wasm artifacts this package ships.
#
# Two targets, one per runtime family, because there is no single wasm-bindgen output that serves
# both a browser and Node without one of them paying for the other's loader:
#
#   pkg/web/    ESM + `WebAssembly.instantiateStreaming`, needs an explicit `init()`
#   pkg/node/   CommonJS + `fs.readFileSync`, instantiates on require
#
# The TypeScript layer hides the difference behind one `init()` that is a no-op on Node, so
# consumer code is identical on both. See docs/architecture.md, "One API, two loaders".
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$PWD"

CORE=""
PROFILE="release"
while [ $# -gt 0 ]; do
  case "$1" in
    # Build against a local engine checkout instead of the pinned tag. For working on the engine
    # itself; the checkout can live anywhere. Mirrors build-native.sh --core in the .NET binding.
    --core) CORE="${2:?--core needs a path}"; shift 2 ;;
    --dev)  PROFILE="dev"; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

command -v cargo      >/dev/null || { echo "cargo not found — see CONTRIBUTING.md, or use .devcontainer/" >&2; exit 1; }
command -v wasm-pack  >/dev/null || { echo "wasm-pack not found — cargo install wasm-pack, or use .devcontainer/" >&2; exit 1; }

# The engine override is a [patch], written into a gitignored .cargo/config.toml rather than into
# Cargo.toml, so a local checkout can never be committed as the dependency by accident.
mkdir -p .cargo
if [ -n "$CORE" ]; then
  CORE_ABS="$(cd "$CORE" && pwd)"
  [ -f "$CORE_ABS/crates/pdf/Cargo.toml" ] || { echo "not a prism-pdf checkout: $CORE_ABS" >&2; exit 1; }
  echo "engine: $CORE_ABS (local checkout)"
  cat > .cargo/config.toml <<PATCH
# Generated by build/build-wasm.sh --core. Gitignored; delete to go back to the pinned tag.
[patch."https://github.com/theunloop/prism-pdf"]
prismpdf = { path = "$CORE_ABS/crates/pdf" }
PATCH
else
  echo "engine: $(cat ENGINE_TAG) (pinned tag)"
  rm -f .cargo/config.toml
fi

rm -rf pkg
for target in web nodejs; do
  out="pkg/$( [ "$target" = nodejs ] && echo node || echo web )"
  echo "--- wasm-pack build --target $target -> $out ---"
  # --no-pack: this crate is not an npm package on its own, it is the payload of one. wasm-pack's
  # generated package.json would otherwise shadow the real one at the repository root.
  wasm-pack build crates/prism-pdf-wasm \
    --"$PROFILE" --target "$target" --out-dir "$ROOT/$out" --out-name prism_pdf --no-pack
  rm -f "$out/.gitignore" "$out/README.md"
done

# This repository is `"type": "module"`, which Node applies to every .js file beneath it —
# including wasm-pack's `nodejs` output, which is CommonJS. Without this marker `require`ing it
# fails with "exports is not defined in ES module scope". A one-line package.json scopes the
# module type to that directory and leaves the ESM `pkg/web` build alone.
echo '{ "type": "commonjs" }' > pkg/node/package.json

echo
echo "--- artifact sizes ---"
for f in pkg/web/prism_pdf_bg.wasm pkg/node/prism_pdf_bg.wasm; do
  gz=$(gzip -9 -c "$f" | wc -c | tr -d ' ')
  printf '%-32s %8s raw  %8s gzipped\n' "$f" \
    "$(du -h "$f" | cut -f1)" "$(( gz / 1024 ))K"
done
